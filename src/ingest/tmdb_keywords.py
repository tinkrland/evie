"""harvest tmdb keywords into the motif proposal queue.

proposals only. nothing here becomes a canonical motif without a
reviewed move into data/vocab/motifs.yaml with an alias table
(docs/motifs-wrangling.md). the queue is deterministic: sorted by
proposal name, sources deduped, no timestamps.

resolving works to tmdb ids is metadata, not taste: ids land in
data/mappings/tmdb-ids.yaml, reviewed like any other proposal.

usage:
    TMDB_API_KEY=... python3 -m src.ingest.tmdb_keywords [--works DIR]

network access lives only in src/ingest. the query path never calls
this module.
"""

import json
import os
import sys
import urllib.parse
import urllib.request
from pathlib import Path

import yaml

root = Path(__file__).resolve().parents[2]
default_works = root / "data" / "works"
default_queue = root / "data" / "motifs" / "queue.yaml"
default_mappings = root / "data" / "mappings" / "tmdb-ids.yaml"
api_base = "https://api.themoviedb.org/3"


def normalise_title(text):
    """lowercase alphanumerics and single spaces, for exact title checks."""
    keep = "".join(c if (c.isalnum() or c == " ") else " " for c in str(text).lower())
    return " ".join(keep.split())


def load_queue(path):
    """read the queue file, or an empty queue if it does not exist yet."""
    path = Path(path)
    if not path.exists():
        return {"version": 1, "proposals": []}
    doc = yaml.safe_load(path.read_text())
    return doc or {"version": 1, "proposals": []}


def merge_proposals(existing, incoming):
    """merge proposal lists deterministically.

    a proposal is identified by its name (lowercase, stripped). sources
    merge by ref; uses counts add. output is sorted by name, sources
    sorted by ref.
    """
    by_name = {}
    for entry in list(existing) + list(incoming):
        name = entry["proposal"]
        slot = by_name.setdefault(name, {"proposal": name, "sources": []})
        for source in entry.get("sources") or []:
            ref = source["ref"]
            match = next((s for s in slot["sources"] if s["ref"] == ref), None)
            if match is None:
                slot["sources"].append(
                    {"kind": source["kind"], "ref": ref, "uses": int(source.get("uses") or 0)}
                )
            else:
                # same ref means the same source reporting again: replace,
                # never add, so repeated harvests stay byte-identical
                match["uses"] = int(source.get("uses") or 0)
    merged = []
    for name in sorted(by_name):
        slot = by_name[name]
        slot["sources"] = sorted(slot["sources"], key=lambda s: s["ref"])
        merged.append(slot)
    return merged


def dump_queue(doc):
    """canonical queue yaml. stable across identical inputs."""
    out = {"version": doc.get("version", 1)}
    proposals = []
    for proposal in sorted(doc["proposals"], key=lambda p: p["proposal"]):
        entry = {"proposal": proposal["proposal"]}
        if "route" in proposal:
            entry["route"] = proposal["route"]
        entry["sources"] = proposal["sources"]
        proposals.append(entry)
    out["proposals"] = proposals
    head = (
        "# motif proposals from external sources. nothing here is canonical.\n"
        "# a reviewed proposal moves into data/vocab/motifs.yaml with an\n"
        "# alias table (docs/motifs-wrangling.md). regenerated by\n"
        "# src/ingest/tmdb_keywords.py; safe to edit by hand.\n"
    )
    return head + yaml.safe_dump(out, sort_keys=False, default_flow_style=False, width=1000)


def load_mappings(path):
    """read data/mappings/tmdb-ids.yaml, or nothing if absent."""
    path = Path(path)
    if not path.exists():
        return {}
    doc = yaml.safe_load(path.read_text()) or {}
    return doc.get("mappings") or {}


def dump_mappings(mappings):
    """canonical mapping yaml, sorted by work id."""
    head = (
        "# proposed tmdb identities for catalog works. reviewed metadata,\n"
        "# not taste: an id is the bridge for keyword and metadata harvest.\n"
        "# regenerated by src/ingest/tmdb_keywords.py; safe to edit by hand.\n"
    )
    out = {"mappings": {k: mappings[k] for k in sorted(mappings)}}
    return head + yaml.safe_dump(out, sort_keys=False, default_flow_style=False, width=1000)


def fetch_json(url):
    """one GET, json back. the only network surface in this module."""
    with urllib.request.urlopen(url, timeout=20) as response:
        return json.loads(response.read().decode("utf-8"))


def search_id(medium, title, year, api_key):
    """resolve one work to a tmdb id by exact normalised title and year."""
    kind = "tv" if medium == "tv" else "movie"
    query = urllib.parse.urlencode({"api_key": api_key, "query": title})
    payload = fetch_json(f"{api_base}/search/{kind}?{query}")
    wanted = normalise_title(title)
    for hit in payload.get("results") or []:
        hit_title = hit.get("name") or hit.get("title") or ""
        if normalise_title(hit_title) != wanted:
            continue
        date = hit.get("first_air_date") or hit.get("release_date") or ""
        hit_year = int(date[:4]) if date[:4].isdigit() else None
        if year and hit_year and abs(int(hit_year) - int(year)) > 1:
            continue
        return hit.get("id"), hit_title, hit_year
    return None, None, None


def fetch_keywords(medium, tmdb_id, api_key):
    """return the tmdb keyword names for one work. network lives here only."""
    kind = "tv" if medium == "tv" else "movie"
    url = f"{api_base}/{kind}/{tmdb_id}/keywords?api_key={api_key}"
    payload = fetch_json(url)
    names = [k["name"] for k in payload.get("keywords") or payload.get("results") or []]
    return sorted(names)


def harvest(works_dir, api_key, mappings_path=default_mappings):
    """collect keyword proposals for every work that resolves to a tmdb id.

    returns (incoming proposals, mappings, unresolved work ids).
    """
    mappings = dict(load_mappings(mappings_path))
    incoming = []
    unresolved = []
    for path in sorted(Path(works_dir).glob("*.yaml")):
        doc = yaml.safe_load(path.read_text()) or {}
        ids = doc.get("external_ids") or {}
        tmdb_id = ids.get("tmdb") or (mappings.get(doc["id"]) or {}).get("tmdb")
        if not tmdb_id:
            tmdb_id, hit_title, hit_year = search_id(
                doc.get("medium", "tv"), doc.get("title", ""), doc.get("first_release"), api_key
            )
            if not tmdb_id:
                unresolved.append(doc["id"])
                continue
            mappings[doc["id"]] = {"tmdb": tmdb_id, "title": hit_title, "year": hit_year}
        for name in fetch_keywords(doc.get("medium", "tv"), tmdb_id, api_key):
            incoming.append(
                {
                    "proposal": name.lower().strip(),
                    "sources": [
                        {"kind": "tmdb-keyword", "ref": f"tmdb-work:{doc['id']}", "uses": 1}
                    ],
                }
            )
    return incoming, mappings, unresolved


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    works_dir = default_works
    if "--works" in argv:
        works_dir = Path(argv[argv.index("--works") + 1])
    api_key = os.environ.get("TMDB_API_KEY")
    if not api_key:
        print("tmdb keyword harvest needs TMDB_API_KEY in the environment.", file=sys.stderr)
        print("the pipeline is built and the queue is seeded; add the key and rerun.", file=sys.stderr)
        return 2
    doc = load_queue(default_queue)
    incoming, mappings, unresolved = harvest(works_dir, api_key)
    merged = merge_proposals(doc["proposals"], incoming)
    default_queue.parent.mkdir(parents=True, exist_ok=True)
    default_queue.write_text(dump_queue({"version": 1, "proposals": merged}))
    default_mappings.parent.mkdir(parents=True, exist_ok=True)
    default_mappings.write_text(dump_mappings(mappings))
    print(f"resolved {len(mappings)} works, unresolved {len(unresolved)}")
    for wid in unresolved:
        print(f"  unresolved: {wid}")
    print(f"queue now holds {len(merged)} proposals at {default_queue}")
    top = sorted(merged, key=lambda p: (-sum(s["uses"] for s in p["sources"]), p["proposal"]))
    for entry in top[:20]:
        uses = sum(s["uses"] for s in entry["sources"])
        print(f"  {entry['proposal']} ({uses} works)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
